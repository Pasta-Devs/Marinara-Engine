// Sandbox engine: the same build run against a copied, sanitized store on its own port.
//
// Isolation, in layers:
// - Own DATA_DIR / FILE_STORAGE_DIR / LOG_DIR and its own env file (MARINARA_ENV_FILE), bound to 127.0.0.1 only.
// - HOME / USERPROFILE / APPDATA / LOCALAPPDATA / XDG_* / CODEX_HOME / CLAUDE_CONFIG_DIR point into the sandbox, so
//   subscription logins (Codex/ChatGPT, Claude Code, CLI-based providers) do not exist there and every such model call
//   fails at once instead of spending quota.
// - API keys and other credential-looking fields are blanked, and remote base URLs point at a closed local port, in
//   the copied connections table. Discord and other webhooks are removed from copied chats.
// - Credential-looking environment variables of the caller are not passed on.
// - Updates cannot be applied from the sandbox (UPDATES_APPLY_DISABLED) and no default connection is seeded.
// Consequence: the sandbox is for prompt previews, UI checks, code verification and restart testing, not for real
// model replies.
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { basename, isAbsolute, join, relative, resolve } from "node:path";
import { IS_WINDOWS, LIVE_DATA_DIR, SANDBOX_DIR, SANDBOX_PORT, SERVER_DIR } from "./config.mjs";
import { startDetached, writePidFile } from "./proc.mjs";

const DATA = join(SANDBOX_DIR, "data");
const STORAGE = join(DATA, "storage");
const HOME = join(SANDBOX_DIR, "home");
const ENV_FILE = join(SANDBOX_DIR, ".env");
export const SANDBOX_LOG = join(SANDBOX_DIR, "sandbox.log");
const META_FILE = join(SANDBOX_DIR, "sandbox.json");
const BLACKHOLE = "http://127.0.0.1:9/sandbox-blocked/v1";
const SECRET_FIELD = /api_?key|secret|token|password|credential/i;
const SECRET_ENV = /api_?key|token|secret|password|passwd|credential|cookie|auth|session|private_?key|encryption_?key/i;

/** Refuse any layout where the sandbox and the live data could be the same folder or nested in each other. */
function assertSeparateFromLive() {
  const live = resolve(LIVE_DATA_DIR);
  const sandbox = resolve(DATA);
  const inside = (parent, child) => {
    const rel = relative(parent, child);
    return rel === "" || (!rel.startsWith("..") && !isAbsolute(rel));
  };
  if (inside(live, sandbox) || inside(sandbox, live)) {
    throw new Error(`sandbox data (${sandbox}) must not be the live data folder (${live}) or inside it`);
  }
}

function sandboxEnv() {
  return {
    NODE_ENV: "production",
    PORT: String(SANDBOX_PORT),
    HOST: "127.0.0.1",
    DATA_DIR: DATA,
    FILE_STORAGE_DIR: STORAGE,
    LOG_DIR: join(DATA, "logs"),
    AUTO_OPEN_BROWSER: "false",
    UPDATES_APPLY_DISABLED: "true",
    AUTO_CREATE_DEFAULT_CONNECTION: "false",
  };
}

function writeEnvFile() {
  const lines = Object.entries(sandboxEnv()).map(([k, v]) => `${k}="${v.replace(/\\/g, "/")}"`);
  writeFileSync(ENV_FILE, `# Marinara sandbox (generated by tools/dev-mcp). Never point this at live data.\n${lines.join("\n")}\n`);
}

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

/** Apply `fn` to every row of every shard of a copied table, rewriting shards that changed. */
function rewriteRows(table, fn) {
  const dir = join(STORAGE, "tables", table);
  if (!existsSync(dir)) return 0;
  let changed = 0;
  for (const name of readdirSync(dir)) {
    if (!name.endsWith(".json")) continue;
    const path = join(dir, name);
    const data = readJson(path);
    const rows = Array.isArray(data)
      ? data
      : Array.isArray(data?.rows)
        ? data.rows
        : data && typeof data === "object" && "id" in data
          ? [data]
          : Object.values(data?.rows ?? data ?? {});
    let dirty = false;
    for (const row of rows) if (row && typeof row === "object" && fn(row)) dirty = true;
    if (dirty) {
      writeFileSync(path, JSON.stringify(data));
      changed += 1;
    }
  }
  return changed;
}

function sanitize() {
  const connections = rewriteRows("api_connections", (row) => {
    let dirty = false;
    // Every credential-looking field (apiKeyEncrypted today); blanked, not deleted, so the row stays valid.
    for (const key of Object.keys(row).filter((k) => SECRET_FIELD.test(k))) {
      if (typeof row[key] === "string" && row[key]) {
        row[key] = "";
        dirty = true;
      }
    }
    // Some providers answer without a key (a public model list, for example), so also point every remote base URL at
    // a closed local port. Subscription providers have no base URL; their logins are hidden by the home redirect.
    for (const key of Object.keys(row).filter((k) => /base_?url|endpoint/i.test(k))) {
      if (typeof row[key] === "string" && /^https?:[/][/]/i.test(row[key]) && !row[key].includes("sandbox-blocked")) {
        row[key] = BLACKHOLE;
        dirty = true;
      }
    }
    return dirty;
  });
  const chats = rewriteRows("chats", (row) => {
    const raw = row.metadata;
    let meta;
    try {
      meta = typeof raw === "string" ? JSON.parse(raw || "{}") : raw;
    } catch {
      return false;
    }
    if (!meta || typeof meta !== "object") return false;
    const hooks = Object.keys(meta).filter((k) => /discord|webhook/i.test(k));
    if (!hooks.length) return false;
    for (const key of hooks) delete meta[key];
    row.metadata = typeof raw === "string" ? JSON.stringify(meta) : meta;
    return true;
  });
  for (const name of readdirSync(STORAGE)) {
    if (name.startsWith(".writer-lease")) rmSync(join(STORAGE, name), { recursive: true, force: true });
  }
  return { connectionShardsSanitized: connections, chatShardsWithWebhooksRemoved: chats };
}

const SKIP = (name) => name.endsWith(".bak") || name.endsWith(".prepaint") || name.startsWith(".writer-lease");

/** Mirror the live store into the sandbox. Windows uses robocopy (multi-threaded); elsewhere a Node copy. */
function mirror(source, target) {
  if (IS_WINDOWS) {
    let code = 0;
    try {
      execFileSync(
        "robocopy",
        [source, target, "/MIR", "/R:2", "/W:1", "/MT:8", "/NFL", "/NDL", "/NJH", "/NJS", "/NP",
          "/XF", "*.bak", "*.prepaint", ".writer-lease*", "/XD", ".writer-lease"],
        { windowsHide: true, stdio: "ignore" },
      );
    } catch (error) {
      code = typeof error.status === "number" ? error.status : 16;
    }
    // robocopy: 0-7 are success variants, 8 and above are failures.
    if (code >= 8) throw new Error(`robocopy failed with code ${code}`);
    return;
  }
  rmSync(target, { recursive: true, force: true });
  cpSync(source, target, { recursive: true, filter: (src) => !SKIP(basename(src)) });
}

/** Copy the live store (not images or other assets) into the sandbox and sanitize it. The live store is only read. */
export function refreshSandboxData() {
  assertSeparateFromLive();
  mkdirSync(DATA, { recursive: true });
  mkdirSync(HOME, { recursive: true });
  const source = join(LIVE_DATA_DIR, "storage");
  if (!existsSync(source)) throw new Error(`live storage not found at ${source}`);
  // The marker is written only after sanitizing succeeds; startSandboxProcess refuses to run without it.
  rmSync(META_FILE, { force: true });
  mirror(source, STORAGE);
  writeEnvFile();
  const sanitized = sanitize();
  const meta = { refreshedAt: new Date().toISOString(), source, port: SANDBOX_PORT, ...sanitized };
  writeFileSync(META_FILE, JSON.stringify(meta, null, 2));
  return meta;
}

export function sandboxInfo() {
  return {
    dir: SANDBOX_DIR,
    port: SANDBOX_PORT,
    exists: existsSync(STORAGE),
    ...(existsSync(META_FILE) ? readJson(META_FILE) : {}),
    storageModified: existsSync(STORAGE) ? new Date(statSync(STORAGE).mtimeMs).toISOString() : null,
    runningDist: existsSync(join(SANDBOX_DIR, "dist.txt")) ? readFileSync(join(SANDBOX_DIR, "dist.txt"), "utf8") : null,
  };
}

/** The caller's environment without anything that looks like a credential, with every home folder redirected. */
function isolatedEnv() {
  const inherited = Object.fromEntries(Object.entries(process.env).filter(([key]) => !SECRET_ENV.test(key)));
  return {
    ...inherited,
    ...sandboxEnv(),
    MARINARA_ENV_FILE: ENV_FILE,
    HOME,
    USERPROFILE: HOME,
    APPDATA: join(HOME, "AppData", "Roaming"),
    LOCALAPPDATA: join(HOME, "AppData", "Local"),
    XDG_CONFIG_HOME: join(HOME, ".config"),
    XDG_DATA_HOME: join(HOME, ".local", "share"),
    XDG_CACHE_HOME: join(HOME, ".cache"),
    XDG_STATE_HOME: join(HOME, ".local", "state"),
    CODEX_HOME: join(HOME, ".codex"),
    CLAUDE_CONFIG_DIR: join(HOME, ".claude"),
  };
}

/**
 * Start the sandbox server (detached, output in sandbox.log) through the same run-server supervisor the launchers
 * use. The caller waits for health. `distDir` (relative to packages/server, default "dist") lets a developer test a
 * private build such as "dist-sandbox" without replacing the live engine's dist.
 */
/** The build folder the sandbox last ran (sandbox_refresh records it), so a plain restart keeps using it. */
function recordedDist() {
  try {
    const value = readFileSync(join(SANDBOX_DIR, "dist.txt"), "utf8").trim();
    return /^dist[\w-]*$/.test(value) ? value : null;
  } catch {
    return null;
  }
}

export async function startSandboxProcess(distDir = recordedDist() || process.env.MARINARA_DEV_SANDBOX_DIST || "dist") {
  if (!/^dist[\w-]*$/.test(distDir)) throw new Error(`invalid dist folder name ${distDir}`);
  if (!existsSync(join(SERVER_DIR, distDir, "index.js"))) throw new Error(`no ${distDir}/index.js in packages/server`);
  if (!existsSync(STORAGE) || !existsSync(META_FILE)) {
    throw new Error("the sandbox has no sanitized data yet; run sandbox_refresh first");
  }
  assertSeparateFromLive();
  mkdirSync(HOME, { recursive: true });
  writeFileSync(join(SANDBOX_DIR, "dist.txt"), distDir);
  writeEnvFile();
  const pid = await startDetached({
    cwd: SERVER_DIR,
    args: ["../../scripts/run-server.mjs", `${distDir}/index.js`],
    env: isolatedEnv(),
    outLog: SANDBOX_LOG,
    errLog: SANDBOX_LOG,
  });
  writePidFile(SANDBOX_PORT, pid);
  return pid;
}

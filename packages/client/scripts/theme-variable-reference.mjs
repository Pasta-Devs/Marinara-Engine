/**
 * Writes src/styles/theme-variables.generated.md: every --ov-*, --mari-* and --marinara-*
 * custom property the app's stylesheets define, with the files that define it.
 * Run `node scripts/theme-variable-reference.mjs` after adding or renaming a variable.
 * The stable, documented subset is in src/styles/README-theming.md; the rest may change.
 */
import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const stylesDir = join(root, "src", "styles");

function cssFiles(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return cssFiles(path);
    return name.endsWith(".css") ? [path] : [];
  });
}

const found = new Map();
for (const file of cssFiles(stylesDir)) {
  const css = readFileSync(file, "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  for (const match of css.matchAll(/(--(?:ov|mari|marinara)-[a-z0-9-]+)\s*:/g)) {
    const files = found.get(match[1]) ?? new Set();
    files.add(relative(stylesDir, file).replace(/\\/g, "/"));
    found.set(match[1], files);
  }
}

const groups = { "--mari-": [], "--ov-": [], "--marinara-": [] };
for (const name of [...found.keys()].sort()) {
  const prefix = Object.keys(groups).find((p) => name.startsWith(p));
  groups[prefix].push(`| \`${name}\` | ${[...found.get(name)].sort().join(", ")} |`);
}

const out = [
  "# Theme variable reference (generated)",
  "",
  "Generated by `scripts/theme-variable-reference.mjs`. Do not edit by hand.",
  "Only the variables in README-theming.md are a stable contract; everything else here is",
  "internal and can change between releases.",
  "",
];
for (const [prefix, rows] of Object.entries(groups)) {
  out.push(`## \`${prefix}*\` (${rows.length})`, "", "| Variable | Defined in |", "| --- | --- |", ...rows, "");
}
writeFileSync(join(stylesDir, "theme-variables.generated.md"), out.join("\n"));
console.log(`theme variables: ${found.size}`);

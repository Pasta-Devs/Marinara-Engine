import type { CombatAiHints } from "../features/combat-ai.js";
import type { CombatStartPlace } from "../features/ruleset-combat/deploy.js";
// ──────────────────────────────────────────────
// Combat Encounter Types
// ──────────────────────────────────────────────
// Modeled after RPG Companion's encounter system:
// A separate turn-based combat modal that runs
// alongside the main roleplay, producing a summary
// that gets injected back into the chat.
// ──────────────────────────────────────────────

import type { MusicEnemyTier } from "../utils/music-score.js";
import type { TacticalMovementMode } from "../features/tactical-combat/types.js";

/** Attack definition for party members and enemies. */
export interface CombatAttack {
  projectile?: boolean;
  requiresSight?: boolean;
  areaRadius?: number;
  friendlyFire?: boolean;
  targetScope?: "single" | "all-enemies";
  spell?: boolean;
  reaction?: "counterspell" | "guard";
  range?: number;
  slotLevel?: number;
  legendaryCost?: number;
  kind?: "attack" | "heal" | "buff" | "debuff";
  mpCost?: number;
  name: string;
  type: "single-target" | "AoE" | "both";
  /** Optional combat tuning generated by the GM. */
  description?: string;
  power?: number;
  cooldown?: number;
  element?: string;
  statusEffect?: string;
}

/** A status effect applied to a combatant. */
export interface CombatStatus {
  name: string;
  emoji: string;
  duration: number;
  modifier?: number;
  stat?: "attack" | "defense" | "speed" | "hp";
}

/** A player inventory item interpreted for this specific encounter. */
export interface CombatItemEffect {
  name: string;
  target: "self" | "ally" | "enemy" | "any";
  type: "heal" | "damage" | "buff" | "debuff" | "status" | "utility";
  description: string;
  power?: number;
  element?: string;
  status?: CombatStatus;
  consumes?: boolean;
  /** Worked out by the Engine from one of the game's ruleset items rather than guessed by a model:
   *  its `power` is the share of the target's maximum health it heals or harms. */
  ruleset?: true;
  /** One of the ruleset's items that holds charges: what a use spends of the most it holds. A fight
   *  offers it while a use is left, and spends charges rather than the item. */
  /** `rolled` (1.573): the dice a stack is found holding, rather than full. */
  charges?: { cost: number; max: number; rolled?: string };
  /** Set by the Engine on the one use whose gate its user failed: the item is spent and does nothing,
   *  and this is what the log says. */
  failed?: string;
  /** One of the ruleset's items used only from a stack that is worn (it takes slots) and bound (it
   *  binds), as a ruleset's own fight uses it. */
  wear?: { equipped?: true; bound?: true };
  /** One of the ruleset's items drawn as it is used (Capability API 1.808): used while only carried,
   *  and put on as it is used. */
  draws?: true;
}

/** One generated in-combat dialogue cue. */
export interface CombatDialogueCue {
  speaker: string;
  content: string;
  type: "main" | "side" | "extra" | "thought" | "whisper";
  expression?: string;
  target?: string;
  trigger:
    | "intro"
    | "round"
    | "attack"
    | "hit"
    | "charge"
    | "phase_75"
    | "phase_50"
    | "phase_25"
    | "low_hp"
    | "victory"
    | "defeat";
  round?: number;
  everyNRounds?: number;
}

/** Optional boss/special encounter rule generated by the GM. */
export interface CombatMechanic {
  name: string;
  description: string;
  ownerName?: string;
  trigger: "round_interval" | "hp_threshold" | "on_hit" | "on_attack" | "passive";
  interval?: number;
  hpThreshold?: number;
  counterplay?: string;
  effectType?: "damage_all" | "damage_one" | "buff_self" | "debuff_party" | "status_party" | "status_enemy";
  power?: number;
  element?: string;
  status?: CombatStatus;
}

/** Optional image generation request for special encounters. */
export interface CombatVisualRequest {
  isBossFight?: boolean;
  /** Encounter classification for context-bound music (#5161): common fights,
   *  minibosses (elites/named threats), true bosses, and special story
   *  encounters each get their own persistent track. Falls back from
   *  isBossFight when absent. */
  encounterTier?: MusicEnemyTier;
  enemyImagePrompts?: Array<{ name: string; prompt: string }>;
  backgroundPrompt?: string;
  illustrationPrompt?: string;
  slug?: string;
}

/** A lasting entry somebody set up before a fight (1.462): a ward, a glyph, hallowed ground. `at`
 *  is where they stand, or between them and their foes; `stores` names what a spell glyph holds. */
export interface CombatStandingEntry {
  entry: string;
  at?: "self" | "between";
  stores?: string;
  /** Who a standing entry with no zone was cast on (1.465), by name. */
  on?: string[];
  /** The creature type a ward that works on one sort works on (1.466), or an entry names (1.487). */
  kind?: string;
  /** The way an entry done one of several ways is done (1.487): the creature Find Familiar calls. */
  mode?: string;
}

/** A member of the player's party. */
export interface CombatPartyMember {
  /** Caught unaware as the fight begins (1.237); a ruleset fight reads it. */
  surprised?: boolean;
  /** Where the story put them as it begins (2026-10-24), when it did; a ruleset fight reads it. */
  start?: CombatStartPlace;
  /** What they set up before the fight, standing as it begins (1.462); a ruleset fight reads it. */
  standing?: CombatStandingEntry[];
  projectile?: boolean;
  requiresSight?: boolean;
  spellSlots?: Record<string, number>;
  aiHints?: CombatAiHints;
  name: string;
  hp: number;
  maxHp: number;
  attacks: CombatAttack[];
  items: string[];
  statuses: CombatStatus[];
  isPlayer: boolean;
  /** Tactical-combat class hint (fighter/knight/rogue/archer/mage/healer). Classic combat ignores this. */
  class?: string;
  /** Tactical traversal rule. Classic combat ignores this; missing means walk. */
  movementMode?: TacticalMovementMode;
}

/** An enemy in the encounter. */
/** An opponent in the ruleset's own terms, for a fight the game's ruleset resolves: a bestiary
 *  reference, the rung of the threat scale it belongs on, and a stat block written for it. The
 *  encounter blueprint carries them to the fight, where the SERVER reads them; `proposed` stays
 *  `unknown` on purpose, because it is a model's text until the server has validated and clamped
 *  it. Every other fight ignores all three. */
export interface RulesetEncounterBlueprint {
  /** Caught unaware as the fight begins (1.237); a ruleset fight reads it. */
  surprised?: boolean;
  /** What it set up before the fight, standing as it begins (1.462); a ruleset fight reads it. */
  standing?: CombatStandingEntry[];
  /** Fights in its own lair (1.315): its lair actions are taken. A ruleset fight reads it. */
  inLair?: boolean;
  /** Where the Game Master starts it on the board (2026-10-24); a ruleset fight reads it. */
  start?: CombatStartPlace;
  /** What the Game Master gave it to have on it (1.795), the ruleset's items by name, one a line; a
   *  ruleset fight reads it in place of what its bestiary entry rolls for. */
  carrying?: string[];
  creature?: string;
  /** What an invented one is (a ruleset's creature type id); a ruleset fight reads it. */
  creatureType?: string;
  tier?: string;
  proposed?: unknown;
}

export interface CombatEnemy extends RulesetEncounterBlueprint {
  projectile?: boolean;
  requiresSight?: boolean;
  boss?: import("../features/combat-director.js").CombatBoss;
  spellSlots?: Record<string, number>;
  aiHints?: CombatAiHints;
  mp?: number;
  maxMp?: number;
  name: string;
  hp: number;
  maxHp: number;
  attacks: CombatAttack[];
  statuses: CombatStatus[];
  description: string;
  sprite: string;
  /** Tactical-combat class hint (fighter/knight/rogue/archer/mage/healer). Classic combat ignores this. */
  class?: string;
  /** Tactical traversal rule. Classic combat ignores this; missing means walk. */
  movementMode?: TacticalMovementMode;
}

/** AI-chosen visual styling hints for the combat environment. */
export interface CombatStyleNotes {
  environmentType: string;
  atmosphere: string;
  timeOfDay: string;
  weather: string;
}

/** Full combat state returned by the init prompt. */
export interface CombatInitState {
  party: CombatPartyMember[];
  enemies: CombatEnemy[];
  environment: string;
  styleNotes: CombatStyleNotes;
  itemEffects?: CombatItemEffect[];
  dialogueCues?: CombatDialogueCue[];
  mechanics?: CombatMechanic[];
  visuals?: CombatVisualRequest;
}

/** An action taken by an enemy during a turn. */
export interface CombatEnemyAction {
  enemyName: string;
  action: string;
  target: string;
}

/** An action taken by a non-player party member during a turn. */
export interface CombatPartyAction {
  memberName: string;
  action: string;
  target: string;
}

/** Updated player actions (attacks/items may change mid-combat). */
export interface CombatPlayerActions {
  attacks: CombatAttack[];
  items: string[];
}

/** Result returned by the combat action prompt. */
export interface CombatActionResult {
  combatStats: {
    party: CombatPartyMember[];
    enemies: CombatEnemy[];
  };
  playerActions: CombatPlayerActions;
  enemyActions: CombatEnemyAction[];
  partyActions: CombatPartyAction[];
  narrative: string;
  combatEnd?: boolean;
  result?: "victory" | "defeat" | "fled" | "interrupted";
}

/** An entry in the encounter log, tracked per-turn. */
export interface EncounterLogEntry {
  timestamp: number;
  action: string;
  result: string;
}

/** Narrative style preferences for combat and summary text. */
export interface NarrativeStyle {
  tense: "present" | "past";
  person: "first" | "second" | "third";
  narration: "omniscient" | "limited";
  pov: string;
}

/** User-configurable encounter settings. */
export interface EncounterSettings {
  combatNarrative: NarrativeStyle;
  summaryNarrative: NarrativeStyle;
  historyDepth: number;
}

// ──────────────────────────────────────────────
// API Request / Response Types
// ──────────────────────────────────────────────

/** Payload for POST /api/encounter/init */
export interface EncounterInitRequest {
  chatId: string;
  connectionId: string | null;
  settings: EncounterSettings;
  /** Optional spellbook lorebook ID to inject spell/attack data into combat */
  spellbookId?: string | null;
  /** When enabled, log the generated combat request/response in the server console. */
  debugMode?: boolean;
}

/** Response from POST /api/encounter/init */
export interface EncounterInitResponse {
  combatState: CombatInitState;
}

/** Payload for POST /api/encounter/action */
export interface EncounterActionRequest {
  chatId: string;
  connectionId: string | null;
  action: string;
  combatStats: {
    party: CombatPartyMember[];
    enemies: CombatEnemy[];
    environment: string;
  };
  playerActions: CombatPlayerActions | null;
  encounterLog: EncounterLogEntry[];
  settings: EncounterSettings;
  /** Optional spellbook lorebook ID to inject spell/attack data into combat */
  spellbookId?: string | null;
}

/** Response from POST /api/encounter/action */
export interface EncounterActionResponse {
  result: CombatActionResult;
  /** True when the model/API produced no usable combat turn and state should not advance. */
  invalid?: boolean;
}

/** Payload for POST /api/encounter/summary */
export interface EncounterSummaryRequest {
  chatId: string;
  connectionId: string | null;
  encounterLog: EncounterLogEntry[];
  result: "victory" | "defeat" | "fled" | "interrupted";
  settings: EncounterSettings;
}

/** Response from POST /api/encounter/summary */
export interface EncounterSummaryResponse {
  summary: string;
  messageId: string;
}
